import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export function generateConferenceImport(manifest) {
    if (!Array.isArray(manifest.conferences) || !manifest.conferences.length) throw new Error('No conferences to import.');
    const ids = new Set(), names = new Set();
    const conferences = manifest.conferences.map(c => {
        const name = typeof c.name === 'string' ? c.name.trim().replace(/\s+/g, ' ').toLowerCase() : '';
        if (typeof c.id !== 'string' || !c.id.trim() || !name || ids.has(c.id) || names.has(name)) {
            throw new Error('Conference IDs and normalized names must be nonempty and unique.');
        }
        if (!Array.isArray(c.tags) || !c.tags.every(tag => typeof tag === 'string') || typeof c.note !== 'string' || typeof c.timezone !== 'string') {
            throw new Error('Invalid conference metadata: ' + c.id);
        }
        ids.add(c.id); names.add(name);
        return { id: c.id, name: c.name, site_url: c.site, location: c.location,
            conf_start_date: c.dates?.conf_start ?? null, conf_end_date: c.dates?.conf_end ?? null,
            areas: c.areas, tags: c.tags, note: c.note, timezone: c.timezone,
            deadlines: c.deadlines?.map(d => ({ type: d.type, due: d.due })) };
    });
    const json = JSON.stringify(conferences, null, 2);
    let quote = '$conference_data$';
    while (json.includes(quote)) quote = quote.slice(0, -1) + '_$';
    let block = '$conference_import$';
    while (json.includes(block)) block = block.slice(0, -1) + '_$';
    return `-- Generated by node scripts/generate-conference-import.mjs; edit data/ai-conferences.json.
-- Run supabase_schema.sql first. Additive: existing records and metadata are preserved.
-- Ambiguous identities abort the entire import; review them manually before retrying.
begin;
lock table public.conferences, public.deadlines in share row exclusive mode;
do ${block}
declare c jsonb; d jsonb; matches text[]; target text; normalized_name text;
begin
    for c in select value from jsonb_array_elements(${quote}${json}${quote}::jsonb) loop
        if not public.valid_conference_payload(c) or not public.valid_deadlines(c->'deadlines') then
            raise exception 'Invalid conference payload: %', c->>'id';
        end if;
        normalized_name := lower(regexp_replace(btrim(c->>'name'), '[[:space:]]+', ' ', 'g'));
        select array_agg(id order by id) into matches from public.conferences
        where id=c->>'id' or lower(regexp_replace(btrim(name), '[[:space:]]+', ' ', 'g'))=normalized_name;
        if cardinality(matches) > 1 then
            raise exception 'Ambiguous conference identity: % matches %', c->>'id', matches;
        end if;
        if exists(select 1 from public.conferences where id=c->>'id'
                  and lower(regexp_replace(btrim(name), '[[:space:]]+', ' ', 'g'))<>normalized_name) then
            raise exception 'Conference ID belongs to another name: %', c->>'id';
        end if;
        target := matches[1];
        if target is null then
            target := c->>'id';
            insert into public.conferences(id,name,site_url,location,conf_start_date,conf_end_date,areas,tags,note,timezone)
            values(target,c->>'name',c->>'site_url',c->>'location',(c->>'conf_start_date')::date,
                (c->>'conf_end_date')::date,c->'areas',array(select jsonb_array_elements_text(c->'tags')),c->>'note',c->>'timezone');
        end if;
        for d in select value from jsonb_array_elements(c->'deadlines') loop
            if not exists(select 1 from public.deadlines where conference_id=target and due_date=(d->>'due')::timestamptz) then
                insert into public.deadlines(conference_id,deadline_type,due_date)
                values(target,d->>'type',(d->>'due')::timestamptz);
            end if;
        end loop;
    end loop;
end;
${block};
commit;
`;
}

